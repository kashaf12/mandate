import { Test, TestingModule } from '@nestjs/testing';
import { NotFoundException, ConflictException } from '@nestjs/common';
import { OrganizationsController } from './organizations.controller';
import { OrganizationsService } from './organizations.service';
import { CreateOrganizationDto } from './dto/create-organization.dto';
import * as schema from '../database/schema';

describe('OrganizationsController', () => {
  let controller: OrganizationsController;
  let mockService: {
    create: jest.Mock;
    findByOrgId: jest.Mock;
    findAll: jest.Mock;
    update: jest.Mock;
  };

  const mockOrg: schema.Organization = {
    id: 'uuid-123',
    orgId: 'acme',
    name: 'Acme Corporation',
    createdAt: new Date('2024-01-01'),
    updatedAt: new Date('2024-01-01'),
  };

  beforeEach(async () => {
    mockService = {
      create: jest.fn(),
      findByOrgId: jest.fn(),
      findAll: jest.fn(),
      update: jest.fn(),
    };

    const module: TestingModule = await Test.createTestingModule({
      controllers: [OrganizationsController],
      providers: [
        {
          provide: OrganizationsService,
          useValue: mockService,
        },
      ],
    }).compile();

    controller = module.get<OrganizationsController>(OrganizationsController);
  });

  afterEach(() => {
    jest.clearAllMocks();
  });

  describe('create', () => {
    it('should create organization with custom orgId', async () => {
      const dto: CreateOrganizationDto = {
        name: 'Acme Corporation',
        orgId: 'acme',
      };

      mockService.create.mockResolvedValue(mockOrg);

      const result = await controller.create(dto);

      expect(result).toEqual(mockOrg);
      expect(mockService.create).toHaveBeenCalledWith(dto);
      expect(mockService.create).toHaveBeenCalledTimes(1);
    });

    it('should create organization without orgId', async () => {
      const dto: CreateOrganizationDto = {
        name: 'Acme Corporation',
      };

      const autoGeneratedOrg: schema.Organization = {
        ...mockOrg,
        orgId: 'org-abc123xyz789',
      };

      mockService.create.mockResolvedValue(autoGeneratedOrg);

      const result = await controller.create(dto);

      expect(result).toEqual(autoGeneratedOrg);
      expect(mockService.create).toHaveBeenCalledWith(dto);
    });

    it('should propagate ConflictException on duplicate orgId', async () => {
      const dto: CreateOrganizationDto = {
        name: 'Acme Corporation',
        orgId: 'acme',
      };

      mockService.create.mockRejectedValue(
        new ConflictException("Organization with ID 'acme' already exists"),
      );

      await expect(controller.create(dto)).rejects.toThrow(ConflictException);
      await expect(controller.create(dto)).rejects.toThrow(
        "Organization with ID 'acme' already exists",
      );
    });

    it('should propagate other errors from service', async () => {
      const dto: CreateOrganizationDto = {
        name: 'Acme Corporation',
        orgId: 'acme',
      };

      mockService.create.mockRejectedValue(
        new Error('Database connection failed'),
      );

      await expect(controller.create(dto)).rejects.toThrow(
        'Database connection failed',
      );
    });
  });

  describe('findAll', () => {
    it('should return all organizations', async () => {
      const mockOrgs: schema.Organization[] = [
        mockOrg,
        {
          ...mockOrg,
          id: 'uuid-456',
          orgId: 'org-abc123',
          name: 'Another Org',
        },
      ];

      mockService.findAll.mockResolvedValue(mockOrgs);

      const result = await controller.findAll();

      expect(result).toEqual(mockOrgs);
      expect(mockService.findAll).toHaveBeenCalledTimes(1);
    });

    it('should return empty array when no organizations exist', async () => {
      mockService.findAll.mockResolvedValue([]);

      const result = await controller.findAll();

      expect(result).toEqual([]);
      expect(mockService.findAll).toHaveBeenCalledTimes(1);
    });
  });

  describe('findOne', () => {
    it('should return organization by orgId', async () => {
      const orgId = 'acme';

      mockService.findByOrgId.mockResolvedValue(mockOrg);

      const result = await controller.findOne(orgId);

      expect(result).toEqual(mockOrg);
      expect(mockService.findByOrgId).toHaveBeenCalledWith(orgId);
      expect(mockService.findByOrgId).toHaveBeenCalledTimes(1);
    });

    it('should throw NotFoundException when organization not found', async () => {
      const orgId = 'nonexistent';

      mockService.findByOrgId.mockRejectedValue(
        new NotFoundException(`Organization ${orgId} not found`),
      );

      await expect(controller.findOne(orgId)).rejects.toThrow(
        NotFoundException,
      );
      await expect(controller.findOne(orgId)).rejects.toThrow(
        'Organization nonexistent not found',
      );
    });
  });

  describe('update', () => {
    it('should update organization name', async () => {
      const orgId = 'acme';
      const newName = 'Acme Corp (Updated)';

      const updatedOrg: schema.Organization = {
        ...mockOrg,
        name: newName,
        updatedAt: new Date('2024-01-02'),
      };

      mockService.update.mockResolvedValue(updatedOrg);

      const result = await controller.update(orgId, newName);

      expect(result).toEqual(updatedOrg);
      expect(mockService.update).toHaveBeenCalledWith(orgId, newName);
      expect(mockService.update).toHaveBeenCalledTimes(1);
    });

    it('should throw NotFoundException when organization not found', async () => {
      const orgId = 'nonexistent';
      const newName = 'New Name';

      mockService.update.mockRejectedValue(
        new NotFoundException(`Organization ${orgId} not found`),
      );

      await expect(controller.update(orgId, newName)).rejects.toThrow(
        NotFoundException,
      );
      await expect(controller.update(orgId, newName)).rejects.toThrow(
        'Organization nonexistent not found',
      );
    });
  });
});
